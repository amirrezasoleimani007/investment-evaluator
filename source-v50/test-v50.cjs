const fs=require('fs'),vm=require('vm'),assert=require('assert/strict'),path=require('path');
const root=__dirname;
const source=fs.readFileSync(path.join(root,'Atieh49.html'),'utf8');
const output=fs.readFileSync(path.join(root,'Atieh50.html'),'utf8');
const script=s=>s.match(/<script type="module">([\s\S]*?)<\/script>/)[1];
const old=script(source),next=script(output);
// The bundled numerical/parser core before import routing must remain byte-identical.
const coreEnd=old.indexOf('async function _S(');
assert(coreEnd>500000);
const coreParts=s=>s.slice(0,s.indexOf('async function _S(')).replace(/function By\([\s\S]*?(?=var Gy=)/,'');
assert.equal(coreParts(next),coreParts(old));
assert.equal(output.match(/globalThis\.__ATIEH_RULEBOOK__=([\s\S]*?)<\/script>/)[1],source.match(/globalThis\.__ATIEH_RULEBOOK__=([\s\S]*?)<\/script>/)[1]);
const context=vm.createContext({f:{},wb:(x,n)=>x===null?'—':Number(x).toFixed(n),Hk:x=>(x*100).toFixed(1)+'%'});
vm.runInContext(fs.readFileSync(path.join(root,'v50-components.js'),'utf8')+';globalThis.format50=V50Numeric;globalThis.value50=V50Value;globalThis.unit50=V50Unit;globalThis.change50=V50Change;',context);
assert.equal(context.format50({value:.072,unit:'درصد'}),'7.2');
assert.equal(context.format50({value:-.298,unit:'درصد'}),'-29.8');
assert.equal(context.format50({value:30339402,unit:'میلیون ریال'}),'30339402');
assert.equal(context.format50({value:0,unit:'درصد'}),'0.0');
assert.equal(context.format50({value:null,unit:'درصد'}),'—');
assert.equal(context.value50({value:.072,unit:'درصد'}),7.199999999999999);
assert.equal(context.unit50({code:'176',unit:'درصد'}),'واحد درصد');
assert.equal(context.change50({percent:null,status:'خروج از زیان'}),'خروج از زیان');
assert.equal(context.change50({percent:0},true),'+0.0%');
const changeFunction=next.match(/function hA\([\s\S]*?(?=function gA)/)[0];
vm.runInContext('let values50;function Rk(e,t,n){return {value:values50[n]}};'+changeFunction+';globalThis.testChange50=(a,b,label="سود خالص")=>{values50={1:a,2:b};return hA(null,null,2,label)};',context);
assert.equal(context.testChange50(-10,20).status,'خروج از زیان');
assert.equal(context.testChange50(-10,20).percent,null);
assert.equal(context.testChange50(0,20).status,'پایه صفر');
assert.equal(context.testChange50(10,20).percent,1);
assert.equal(context.testChange50(20,10).percent,-.5);
assert.equal(context.testChange50(-.2,-.3,'اسپرد ارزش آفرینی').status,'پایه منفی');
const serialization=next.slice(next.indexOf('function By('),next.indexOf('function Hy('));
vm.runInContext(serialization+';globalThis.roundtrip50=x=>Vy(JSON.parse(JSON.stringify(By(x))));',context);
assert.equal(context.roundtrip50(Infinity),Infinity);
assert.equal(context.roundtrip50(-Infinity),-Infinity);
assert.equal(context.roundtrip50(0),0);
assert.throws(()=>context.roundtrip50(NaN));
const css=fs.readFileSync(path.join(root,'v50.css'),'utf8');
assert(css.includes('prefers-reduced-motion:reduce'));
assert(css.includes('@media print'));
console.log('PASS: original numerical core and rulebook unchanged; formatting, baseline, serialization and UI checks.');
